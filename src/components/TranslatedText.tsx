export function translate(de: string, language: "de" | "az"): string {
  if (language === "de") return de;
  const leading = de.match(/^\s*/)?.[0] ?? "";
  const trailing = de.match(/\s*$/)?.[0] ?? "";
  const core = de.trim();
  return leading + (azTranslations[core] ?? core) + trailing;
}

export function T({ children }: { children: string }) {
  const { language } = useLanguage();
  return <>{translate(children, language)}</>;
}

export function useT() {
  const { language } = useLanguage();
  return (value: string) => translate(value, language);
}
